const kp = (...names: string[]) => names.map((n) => `grammar.${n}`)
const kanjiKps = (...chars: string[]) => chars.map((c) => `kanji.${c}`)

const words = (...selectors: string[]) =>
  selectors.map((k) => {
    const v =
      VOCAB.find((x) => x.kanji === k) ??
      (VOCAB.filter((x) => x.kana === k).length === 1
        ? VOCAB.find((x) => x.kana === k)
        : undefined)
    if (!v) throw new Error(`單字庫裡找不到或有歧義：${k}`)
    return { jp: v.kana, kanji: v.kanji, zh: v.zh, accent: v.accent }
  })


