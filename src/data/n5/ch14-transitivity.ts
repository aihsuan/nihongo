/**
 * N5 第 14 章：自動詞與他動詞
 * 對應《完全掌握 N5》單元 28（自動詞・他動詞）、29（自動詞＋ています）、30（〜てあります）。
 *
 * 這一章是「が」和「を」的總結。前面十三章零散教過的助詞用法，
 * 到這裡被同一條規則收攏：**他動詞配を，自動詞配が**。
 *
 * 中文沒有這個區分——「門開了」和「我開門」用的是同一個「開」。
 * 日文有兩個不同的詞（開{あ}く／開{あ}ける），所以這是中文母語者必踩的坑。
 */
