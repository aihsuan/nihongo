const kp = (...names: string[]) => names.map((n) => `grammar.${n}`)
const kanjiKps = (...chars: string[]) => chars.map((c) => `kanji.${c}`)

const words = (...selectors: string[]) =>
  selectors.map((k) => {
    const byKanji = VOCAB.filter((x) => x.kanji === k)
    const byKana = VOCAB.filter((x) => x.kana === k)
    const v = byKanji.length === 1 ? byKanji[0] : byKana.length === 1 ? byKana[0] : undefined
    if (!v) throw new Error(`單字庫裡找不到或有歧義：${k}`)
    return { jp: v.kana, kanji: v.kanji, zh: v.zh, accent: v.accent }
  })

const say = (text: string, speak = text): TableCell => ({ text, speak })
const label = (text: string): TableCell => ({ text })

/* 這一章的填空一律是「が」或「を」二選一，和課本的練習形式一致 */
const gaWoQ = (id: string, prompt: string, answer: 'が' | 'を', explanation: string) =>
  grammarFillQ(id, kp('が-を-使い分け'), prompt, [answer], [answer === 'が' ? 'を' : 'が'], explanation)

