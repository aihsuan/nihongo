const BY_CHAR = new Map(KANJI.map((k) => [k.char, k]))

export function kanji(char: string): Kanji {
  const found = BY_CHAR.get(char)
  if (!found) throw new Error(`漢字資料還沒寫：${char}`)
  return found
}

export const hasKanji = (char: string) => BY_CHAR.has(char)
