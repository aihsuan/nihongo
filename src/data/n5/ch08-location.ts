/**
 * N5 第 8 章：說東西在哪裡
 * 對應《完全掌握 N5》單元 6（位置を表す言葉）與 7（あります／います）。
 *
 * 這一章看起來只是位置詞，實際上藏著整個日文最難的一件事：**は 和 が 的差別**。
 * 「部屋{へや}に 何{なに}が ありますか」和「本{ほん}は どこに ありますか」
 * 用的是同一組詞，但問的事情完全不同。所以第 5 課單獨處理它，不硬塞進第 3 課。
 *
 * 漢字六個（上下左右中外），單字吃「方位」整組十六個字 ——
 * 那是十四組主題裡最後一組完全沒動過的。
 */
