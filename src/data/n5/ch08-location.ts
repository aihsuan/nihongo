const kp = (...names: string[]) => names.map((n) => `grammar.${n}`)
const kanjiKps = (...chars: string[]) => chars.map((c) => `kanji.${c}`)

const words = (...kanaList: string[]) =>
  kanaList.map((k) => {
    const v = VOCAB.find((x) => x.kana === k)
    if (!v) throw new Error(`單字庫裡沒有：${k}`)
    return { jp: v.kana, kanji: v.kanji, zh: v.zh, accent: v.accent }
  })

const say = (text: string, speak = text): TableCell => ({ text, speak })
const label = (text: string): TableCell => ({ text })

