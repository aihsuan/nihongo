/**
 * N5 第 6 章：邀約與提議
 * 對應《完全掌握 N5》單元 14（〜ませんか／〜ましょう 勧誘）與 40（接続詞）。
 *
 * 全 N5 最小的一章，只有三課。但它教的是第一個**社交**功能 ——
 * 前面五章都在描述事實（我是誰、東西在哪、我做了什麼），
 * 這一章第一次要求學習者對另一個人開口提出請求。
 *
 * 日文的邀約用否定疑問（食べませんか）而不是肯定，這對中文母語者極反直覺，
 * 所以第 1 課整課都在處理這一件事。
 */
