/**
 * N5 第 15 章：普通形與名詞修飾
 * 對應《完全掌握 N5》單元 34（丁寧形と普通形）、36（名詞修飾）、
 * 37（〜とき）、38（〜という＋名詞）。
 *
 * N5 最後一個硬的文法點。普通形本身不難 —— 動詞的四種形態第 10 到 13 章都學過了，
 * 這一章只是告訴你「原來那些就是普通形」。
 *
 * 真正的難點是**連體修飾**：日文可以把一整個句子塞到名詞前面當形容詞。
 * 中文的「的」只能接短語，日文可以接完整的主謂結構，這個結構差異要花時間適應。
 */
