/**
 * N5 第 10 章：動詞分類與て形
 * 對應《完全掌握 N5》單元 15（動詞のグループ分け）與 16（て形の作り方）。
 *
 * 這章只有三課，卻是整個 N5 後半的地基 ——
 * 第 11 到 13 章（て形應用、た形、ない形、辭書形）全部建立在「分對類」上面。
 * 分類錯了，後面每一個變化都會錯，而且錯得看不出原因。
 *
 * 所以第 1 課完全不教變化，只教怎麼判斷一個動詞是第幾類。
 */
