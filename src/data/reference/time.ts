import type { TableBlock } from '../../core/types'
import { label, say } from '../cells'
import type { RefCategory, RefSheet } from './types'

const clean = (s: string) => s.replace(/\*\*/g, '').replace(/[{][^}]*[}]/g, '')

/**
 * 把「數字 ＋ 唸法」幾組排成一列，省版面又掃得快。
 * 唸法長的表（日期）用 2 組一列，短的（時、分）用 3 組。
 */
function pairs(items: [string, string][], per = 3): TableBlock['rows'] {
  const rows: TableBlock['rows'] = []
  for (let i = 0; i < items.length; i += per) {
    const row: TableBlock['rows'][number] = []
    for (const [n, reading] of items.slice(i, i + per)) {
      row.push(label(n), say(reading, clean(reading)))
    }
    while (row.length < per * 2) row.push(label(''))
    rows.push(row)
  }
  return rows
}

/** 「數字／唸法」重複 n 次的欄位標題 */
const pairCols = (a: string, b: string, n: number) =>
  Array.from({ length: n }, () => [a, b]).flat()

