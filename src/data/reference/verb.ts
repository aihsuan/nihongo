/* ── 6. 時態 ───────────────────────────────────────────── */

/**
 * 時態一次看完。
 *
 * 上一版把它拆成四處：ます形四格在第 5 章、ています 在第 11 章、
 * 過去進行又在別的地方。學的時候分開沒問題（那時候還沒學て形），
 * 但**速查的時候要的正好是它們排在一起**：想知道「正在讀」怎麼說，
 * 不該翻三張表。
 */
